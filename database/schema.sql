
BEGIN;

CREATE TABLE IF NOT EXISTS public.usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_usuario_ativo ON public.usuario(ativo);

CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    telefone VARCHAR(30),
    email VARCHAR(150) UNIQUE,
    cpf VARCHAR(20),
    endereco VARCHAR(255),
    numero VARCHAR(20),
    complemento VARCHAR(100),
    bairro VARCHAR(100),
    cidade VARCHAR(100),
    estado VARCHAR(2),
    cep VARCHAR(15),
    observacao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_clientes_nome ON public.clientes(nome);
CREATE INDEX IF NOT EXISTS idx_clientes_telefone ON public.clientes(telefone);
CREATE INDEX IF NOT EXISTS idx_clientes_ativo ON public.clientes(ativo);

CREATE TABLE IF NOT EXISTS public.formas_pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

INSERT INTO public.formas_pagamento (nome) VALUES
    ('Pix'),
    ('Dinheiro'),
    ('Cartão de débito'),
    ('Cartão de crédito'),
    ('Transferência')
ON CONFLICT (nome) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.vendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_pedido VARCHAR(30) UNIQUE,
    data_venda DATE NOT NULL DEFAULT CURRENT_DATE,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE SET NULL,
    usuario_id BIGINT REFERENCES public.usuario(id) ON DELETE SET NULL,
    forma_pagamento_id BIGINT REFERENCES public.formas_pagamento(id) ON DELETE SET NULL,
    adicional NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (adicional >= 0),
    bebidas NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (bebidas >= 0),
    frete NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (frete >= 0),
    desconto NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (desconto >= 0),
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    total NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    observacao TEXT,
    status TEXT NOT NULL DEFAULT 'FINALIZADA'
        CHECK (status IN ('ABERTA', 'FINALIZADA', 'CANCELADA')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_vendas_data ON public.vendas(data_venda);
CREATE INDEX IF NOT EXISTS idx_vendas_cliente ON public.vendas(cliente_id);
CREATE INDEX IF NOT EXISTS idx_vendas_usuario ON public.vendas(usuario_id);
CREATE INDEX IF NOT EXISTS idx_vendas_pagamento ON public.vendas(forma_pagamento_id);
CREATE INDEX IF NOT EXISTS idx_vendas_status ON public.vendas(status);

-- Itens sem catalogo: cada linha guarda tamanho, quantidade e preco praticado.
CREATE TABLE IF NOT EXISTS public.venda_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id BIGINT NOT NULL REFERENCES public.vendas(id) ON DELETE CASCADE,
    tamanho TEXT NOT NULL DEFAULT 'UNICO'
        CHECK (tamanho IN ('P', 'M', 'G', 'E', 'S', 'UNICO')),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(10, 2) NOT NULL CHECK (valor_unitario >= 0),
    subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0)
);

ALTER TABLE public.venda_itens
    DROP COLUMN IF EXISTS produto_id;

CREATE INDEX IF NOT EXISTS idx_venda_itens_venda
    ON public.venda_itens(venda_id);

-- Remove os objetos do catalogo antigo; historicos de venda ficam nos itens acima.
DROP VIEW IF EXISTS public.vw_produtos_mais_vendidos;
DROP TABLE IF EXISTS public.produtos;

CREATE OR REPLACE VIEW public.vw_vendas_relatorio AS
SELECT
    v.id,
    v.numero_pedido,
    v.data_venda,
    c.nome AS cliente,
    fp.nome AS forma_pagamento,
    v.subtotal,
    v.adicional,
    v.bebidas,
    v.frete,
    v.desconto,
    v.total,
    v.status
FROM public.vendas AS v
LEFT JOIN public.clientes AS c ON c.id = v.cliente_id
LEFT JOIN public.formas_pagamento AS fp ON fp.id = v.forma_pagamento_id;

ALTER TABLE public.usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.formas_pagamento ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vendas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.venda_itens ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO service_role;
GRANT ALL PRIVILEGES ON TABLE
    public.usuario,
    public.clientes,
    public.formas_pagamento,
    public.vendas,
    public.venda_itens
TO service_role;
GRANT SELECT ON public.vw_vendas_relatorio TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

NOTIFY pgrst, 'reload schema';

COMMIT;
